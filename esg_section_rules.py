# A modest, deterministic retrieval score; avoids sending unrelated most-recent uploads.
def rank_evidence(rows, section, title, limit=4):
    purpose, terms, _ = guidance(section)
    words = list(dict.fromkeys([w.lower() for w in terms.split() if len(w)>=2] + [w.lower() for w in title.split() if len(w)>=2]))
    scored=[]
    for row in rows:
        body=row['body'] or ''
        text=(body+' '+(row['filename'] or '')+' '+(row['location'] or '')).lower()
        score=sum(min(text.count(w),4) * (2 if len(w)>3 else 1) for w in words)
        if score>0:
            scored.append((score,row))
    scored.sort(key=lambda x:(-x[0],x[1]['id']))
    return [r for _,r in scored[:limit]]
